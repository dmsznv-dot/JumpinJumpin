"""Preserve SimReady object geometry; simplify and fit it to a wearable socket.
Run with Python 3.12: build-props.py --cache /path/to/downloaded/assets [ids...]
Dependencies: usd-core numpy pillow trimesh fast-simplification scipy.
Source downloads: fetch.py. Output is self-contained GLB, no runtime textures.
"""
import argparse, json, os
import numpy as np
import trimesh
import fast_simplification
from scipy.spatial import cKDTree
from build import load_asset, rotation, palette, ROOT, HERE

parser=argparse.ArgumentParser()
parser.add_argument('--cache', required=True)
parser.add_argument('ids', nargs='*')
args=parser.parse_args()
specs=json.load(open(os.path.join(HERE,'props.json')))
manifest_path=os.path.join(HERE,'backlog','costume-manifest.mjs')
old=open(manifest_path).read()
manifest=json.loads(old[old.index('{'):old.rindex('}')+1])
for cid,spec in specs.items():
    if args.ids and cid not in args.ids: continue
    tris,colors=load_asset(os.path.join(args.cache,spec['asset']))
    pts=tris.reshape(-1,3) @ rotation(spec.get('rotate',[0,0,0])).T
    # One scale on all axes: preserve handles, holes, thin stems and proportions.
    lo,hi=pts.min(0),pts.max(0)
    pts=(pts-(lo+hi)/2)*spec['size']/max(hi-lo)
    original=pts.copy()
    verts,inv=np.unique(np.round(pts,6),axis=0,return_inverse=True)
    faces=inv.reshape(-1,3)
    budget=spec.get('triangles',2200)
    if len(faces)>budget:
        verts,faces=fast_simplification.simplify(verts.astype(np.float32),faces.astype(np.int32),target_count=budget,agg=5)
    if len(faces)>budget*1.2:
        verts,faces=fast_simplification.simplify(verts.astype(np.float32),faces.astype(np.int32),target_count=budget,agg=8)
    low=trimesh.Trimesh(verts,faces,process=False)
    # Sample source colour near each output vertex, quantize only colour (not shape).
    nearest=cKDTree(original).query(low.vertices)[1]
    sampled=colors.reshape(-1,3)[nearest]
    tones,labels=palette(sampled,min(12,len(sampled)),1.12,.12)
    srgb=tones[labels]
    linear=np.where(srgb<=.04045,srgb/12.92,((srgb+.055)/1.055)**2.4)
    low.visual=trimesh.visual.ColorVisuals(low,vertex_colors=np.c_[(linear*255).round().astype(np.uint8),np.full(len(verts),255,np.uint8)])
    # Bake placement in Body-local space. No extra scaling in runtime.
    lo,hi=low.bounds
    if spec['slot']=='head':
        offset=np.array([0,.77-spec.get('sink',0)-lo[1],-.07])
    else:
        offset=np.array([spec.get('side',.27),spec.get('height',.1),-.69-hi[2]])
    low.apply_translation(offset)
    out=os.path.join(ROOT,'assets','costumes',cid+'.glb')
    low.export(out)
    manifest[cid]={'file':'assets/costumes/'+cid+'.glb','tris':len(faces),'source':spec['asset'],
        'title':spec['title'],'icon':spec['icon'],'slot':spec['slot'],'full':False,
        'palette':['#%02x%02x%02x'%tuple((c*255).round().astype(int)) for c in tones],
        'bounds':low.bounds.round(4).tolist(),'bytes':os.path.getsize(out)}
    print(f'{cid}: {len(tris)} -> {len(faces)} triangles, {os.path.getsize(out)} bytes, bounds {low.bounds.round(2).tolist()}',flush=True)
# Preserve curated ordering and never leave stale retired entries in a full build.
manifest={cid:manifest[cid] for cid in specs if cid in manifest}
with open(manifest_path,'w') as f:
    f.write('// Generated by tools/costumes/build-props.py. NVIDIA SimReady, CC BY 4.0.\nexport const COSTUME_ASSETS = '+json.dumps(manifest,ensure_ascii=False,indent=1)+';\n')
